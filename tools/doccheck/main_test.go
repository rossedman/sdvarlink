package main

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// writeFiles creates each file (path relative to root) with its contents.
func writeFiles(t *testing.T, root string, files map[string]string) {
	t.Helper()
	for name, body := range files {
		path := filepath.Join(root, name)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
}

func TestRun(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name     string
		files    map[string]string
		want     int
		findings []string // substrings expected in stdout
		absent   []string // substrings that must not appear
	}{
		{
			name: "all documented",
			files: map[string]string{
				"a.go": "// Package a is documented.\npackage a\n\n// F does nothing.\nfunc F() {}\n",
			},
			want: 0,
		},
		{
			name: "missing function and method docs",
			files: map[string]string{
				"a.go": "// Package a is documented.\npackage a\n\ntype T struct{}\n\ntype G[K any] struct{}\n\ntype H[K, V any] struct{}\n\nfunc f() {}\n\nfunc (T) m() {}\n\nfunc (*T) p() {}\n\nfunc (G[K]) g() {}\n\nfunc (*H[K, V]) h() {}\n",
			},
			want:     1,
			findings: []string{"a.go:10:1: f has no doc comment", "T.m has no doc comment", "T.p has no doc comment", "G.g has no doc comment", "H.h has no doc comment", "5 missing doc comments"},
		},
		{
			name: "package comment in one file is enough",
			files: map[string]string{
				"a.go": "// Package a is documented.\npackage a\n",
				"b.go": "package a\n",
			},
			want: 0,
		},
		{
			name: "missing package comment",
			files: map[string]string{
				"a.go": "package a\n",
			},
			want:     1,
			findings: []string{"package has no package comment", "1 missing doc comments"},
		},
		{
			name: "tests, generated files, testdata and hidden dirs are skipped",
			files: map[string]string{
				"a.go":               "// Package a is documented.\npackage a\n",
				"a_test.go":          "package a\n\nfunc helper() {}\n",
				"gen.go":             "// Code generated by x. DO NOT EDIT.\n\npackage a\n\nfunc gen() {}\n",
				"testdata/t.go":      "package t\n\nfunc t() {}\n",
				".hidden/h.go":       "package h\n\nfunc h() {}\n",
				"vendor/v/v.go":      "package v\n\nfunc v() {}\n",
				"_skip/s.go":         "package s\n\nfunc s() {}\n",
				"onlygen/gen.go":     "// Code generated by x. DO NOT EDIT.\n\npackage onlygen\n",
				"notes/README.md":    "not go",
				"sub/sub.go":         "// Package sub is documented.\npackage sub\n\n// S does nothing.\nfunc S() {}\n",
				"sub/deeper/deep.go": "// Package deeper is documented.\npackage deeper\n",
			},
			want:   0,
			absent: []string{"helper", "gen", "func t", "h has", "v has", "s has"},
		},
		{
			name: "nested package is checked",
			files: map[string]string{
				"a.go":       "// Package a is documented.\npackage a\n",
				"sub/sub.go": "// Package sub is documented.\npackage sub\n\nfunc s() {}\n",
			},
			want:     1,
			findings: []string{"sub.go:4:1: s has no doc comment"},
		},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			root := t.TempDir()
			writeFiles(t, root, tc.files)
			var stdout, stderr bytes.Buffer
			got := run([]string{root + "/..."}, &stdout, &stderr)
			if got != tc.want {
				t.Fatalf("exit = %d, want %d\nstdout:\n%s\nstderr:\n%s", got, tc.want, stdout.String(), stderr.String())
			}
			if tc.want == 0 && stdout.Len() != 0 {
				t.Errorf("stdout = %q, want empty", stdout.String())
			}
			for _, f := range tc.findings {
				if !strings.Contains(stdout.String(), f) {
					t.Errorf("stdout missing %q:\n%s", f, stdout.String())
				}
			}
			for _, a := range tc.absent {
				if strings.Contains(stdout.String(), a) {
					t.Errorf("stdout has %q:\n%s", a, stdout.String())
				}
			}
		})
	}
}

func TestRunSingleDir(t *testing.T) {
	t.Parallel()
	root := t.TempDir()
	writeFiles(t, root, map[string]string{
		"a.go":       "// Package a is documented.\npackage a\n",
		"sub/sub.go": "package sub\n",
	})
	var stdout, stderr bytes.Buffer
	if got := run([]string{root}, &stdout, &stderr); got != 0 {
		t.Fatalf("exit = %d, want 0 (sub/ is not checked without /...): %s", got, stdout.String())
	}
}

func TestRunDefaultsToCurrentTree(t *testing.T) {
	// Not parallel: run with no args resolves "./..." against the working
	// directory, which is this package's directory under go test.
	var stdout, stderr bytes.Buffer
	if got := run(nil, &stdout, &stderr); got != 0 {
		t.Fatalf("exit = %d, want 0 for doccheck's own package:\n%s%s", got, stdout.String(), stderr.String())
	}
}

func TestRunErrors(t *testing.T) {
	t.Parallel()
	root := t.TempDir()
	writeFiles(t, root, map[string]string{"bad/bad.go": "package bad\n\nfunc {\n"})

	tests := []struct {
		name string
		arg  string
	}{
		{"missing tree", filepath.Join(root, "nope") + "/..."},
		{"missing dir", filepath.Join(root, "nope")},
		{"parse error", filepath.Join(root, "bad")},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			var stdout, stderr bytes.Buffer
			if got := run([]string{tc.arg}, &stdout, &stderr); got != 2 {
				t.Fatalf("exit = %d, want 2", got)
			}
			if !strings.HasPrefix(stderr.String(), "doccheck: ") {
				t.Errorf("stderr = %q, want a doccheck: error", stderr.String())
			}
		})
	}
}
