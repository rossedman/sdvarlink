package gen

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"strings"
)

// Alias generates the systemd/latest/<pkg> package, which re-exports the
// package at importPath (the newest generated release) under a stable
// import path.
func Alias(src []byte, importPath, version string) ([]byte, error) {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, "", src, parser.ParseComments)
	if err != nil {
		return nil, err
	}
	pkg := f.Name.Name
	alias := "v" + version
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by sdvarlink-gen. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "// Package %s re-exports %s, the bindings for the newest\n", pkg, importPath)
	fmt.Fprintf(&b, "// systemd release this module was generated from (v%s). Import it to\n", version)
	fmt.Fprintf(&b, "// track new releases automatically; import a versioned package to pin\n// the oldest systemd you support.\n")
	fmt.Fprintf(&b, "package %s\n\nimport (\n\t\"context\"\n\n\t%s %q\n\t\"github.com/rossedman/sdvarlink/varlink\"\n)\n\n", pkg, alias, importPath)

	var types, consts, vars []string
	for _, d := range f.Decls {
		switch d := d.(type) {
		case *ast.GenDecl:
			for _, spec := range d.Specs {
				switch s := spec.(type) {
				case *ast.TypeSpec:
					if s.Name.IsExported() {
						types = append(types, s.Name.Name)
					}
				case *ast.ValueSpec:
					for _, n := range s.Names {
						if !n.IsExported() {
							continue
						}
						if d.Tok == token.CONST {
							consts = append(consts, n.Name)
						} else {
							vars = append(vars, n.Name)
						}
					}
				}
			}
		case *ast.FuncDecl:
			if d.Recv != nil || !d.Name.IsExported() {
				continue
			}
			var sig bytes.Buffer
			printer.Fprint(&sig, fset, d.Type)
			var args []string
			for _, p := range d.Type.Params.List {
				for _, n := range p.Names {
					a := n.Name
					if _, ok := p.Type.(*ast.Ellipsis); ok {
						a += "..."
					}
					args = append(args, a)
				}
			}
			fmt.Fprintf(&b, "// %s calls %s.%s.\nfunc %s%s {\n\treturn %s.%s(%s)\n}\n\n",
				d.Name.Name, alias, d.Name.Name, d.Name.Name, strings.TrimPrefix(sig.String(), "func"), alias, d.Name.Name, strings.Join(args, ", "))
		}
	}
	if len(types) > 0 {
		b.WriteString("// Types re-exported from the newest release.\ntype (\n")
		for _, t := range types {
			fmt.Fprintf(&b, "\t%s = %s.%s\n", t, alias, t)
		}
		b.WriteString(")\n\n")
	}
	if len(consts) > 0 {
		b.WriteString("// Constants re-exported from the newest release.\nconst (\n")
		for _, c := range consts {
			fmt.Fprintf(&b, "\t%s = %s.%s\n", c, alias, c)
		}
		b.WriteString(")\n\n")
	}
	if len(vars) > 0 {
		b.WriteString("// Variables re-exported from the newest release.\nvar (\n")
		for _, v := range vars {
			fmt.Fprintf(&b, "\t%s = %s.%s\n", v, alias, v)
		}
		b.WriteString(")\n\n")
	}
	b.WriteString("var (\n\t_ context.Context\n\t_ varlink.Caller\n)\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("alias %s: %w\n%s", pkg, err, b.String())
	}
	return out, nil
}
