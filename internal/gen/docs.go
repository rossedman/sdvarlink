package gen

import (
	"fmt"
	"strings"

	"github.com/rossedman/sdvarlink/idl"
)

// Release is one systemd release's interfaces.
type Release struct {
	Version    string
	Interfaces map[string]*idl.Interface
}

// Page is one generated Markdown page, relative to the reference directory.
type Page struct {
	Path     string
	NavTitle string
	Content  string
}

// ReferenceDocs renders an overview page, a per-interface page for every
// interface in the newest release, and an API changes page.
func ReferenceDocs(cfg *Config, releases []Release) []Page {
	newest := releases[len(releases)-1]
	since := map[string]string{}
	methodSince := map[string]string{}
	for _, r := range releases {
		for name, iface := range r.Interfaces {
			if _, ok := since[name]; !ok {
				since[name] = r.Version
			}
			for _, m := range iface.Methods {
				q := name + "." + m.Name
				if _, ok := methodSince[q]; !ok {
					methodSince[q] = r.Version
				}
			}
		}
	}
	names := sortedKeys(newest.Interfaces)

	var pages []Page
	var ov strings.Builder
	ov.WriteString("# Interfaces\n\n")
	ov.WriteString("<!-- Generated by `make docs-reference`. Do not edit. -->\n\n")
	var versions []string
	for _, r := range releases {
		versions = append(versions, "v"+r.Version)
	}
	fmt.Fprintf(&ov, "sdvarlink generates a package for every `io.systemd.*` Varlink interface in each supported systemd release (%s). ", strings.Join(versions, ", "))
	fmt.Fprintf(&ov, "This table lists the interfaces in **systemd v%s**; each page shows methods, types and errors, and the systemd version that introduced them.\n\n", newest.Version)
	ov.WriteString("| Interface | Go package | Methods | Since | Default socket |\n| --- | --- | ---: | --- | --- |\n")
	for _, name := range names {
		iface := newest.Interfaces[name]
		pkg := PackageName(name)
		sock := cfg.Sockets[name]
		if sock == "" {
			sock = "—"
		} else {
			sock = "`" + sock + "`"
		}
		fmt.Fprintf(&ov, "| [`%s`](interfaces/%s.md) | `%s` | %d | v%s | %s |\n", name, pkg, pkg, len(iface.Methods), since[name], sock)
	}
	ov.WriteString("\nImport a versioned package to pin the oldest systemd you support, or `systemd/latest/<pkg>` to follow the newest release:\n\n")
	fmt.Fprintf(&ov, "```go\nimport (\n    \"%s/systemd/v%s/resolve\"   // pinned\n    \"%s/systemd/latest/resolve\" // newest\n)\n```\n", cfg.Module, releases[0].Version, cfg.Module)
	pages = append(pages, Page{Path: "interfaces.md", Content: ov.String()})

	for _, name := range names {
		iface := newest.Interfaces[name]
		pkg := PackageName(name)
		var b strings.Builder
		fmt.Fprintf(&b, "# %s\n\n", name)
		b.WriteString("<!-- Generated by `make docs-reference`. Do not edit. -->\n\n")
		if iface.Doc != "" {
			b.WriteString(iface.Doc + "\n\n")
		}
		fmt.Fprintf(&b, "| Property | Value |\n| --- | --- |\n")
		fmt.Fprintf(&b, "| Go package | [`%s/systemd/latest/%s`](https://pkg.go.dev/%s/systemd/latest/%s) |\n", cfg.Module, pkg, cfg.Module, pkg)
		if s := cfg.Sockets[name]; s != "" {
			fmt.Fprintf(&b, "| Socket | `%s` |\n", s)
		}
		fmt.Fprintf(&b, "| Available since | systemd v%s |\n", since[name])
		fmt.Fprintf(&b, "| Methods · types · errors | %d · %d · %d |\n\n", len(iface.Methods), len(iface.Types), len(iface.Errors))

		if len(iface.Methods) > 0 {
			b.WriteString("## Methods\n\n")
			for _, m := range iface.Methods {
				fmt.Fprintf(&b, "### %s\n\n", m.Name)
				var badges []string
				switch m.More {
				case idl.MoreRequired:
					badges = append(badges, ":material-waves: streaming (requires `more`)")
				case idl.MoreSupported:
					badges = append(badges, ":material-waves: streaming optional")
				}
				if s := methodSince[name+"."+m.Name]; s != since[name] {
					badges = append(badges, ":material-new-box: since v"+s)
				}
				if hasFD(cfg, m.In) || hasFD(cfg, m.Out) {
					badges = append(badges, ":material-file-swap: passes file descriptors")
				}
				if len(badges) > 0 {
					b.WriteString(strings.Join(badges, " · ") + "\n\n")
				}
				if m.Doc != "" {
					b.WriteString(m.Doc + "\n\n")
				}
				b.WriteString("```go\n" + goSignature(m) + "\n```\n\n")
				if len(m.In.Fields) > 0 {
					b.WriteString("**Parameters**\n\n")
					fieldTable(&b, m.In)
				}
				if len(m.Out.Fields) > 0 {
					b.WriteString("**Reply**\n\n")
					fieldTable(&b, m.Out)
				}
			}
		}
		if len(iface.Types) > 0 {
			b.WriteString("## Types\n\n")
			for _, t := range iface.Types {
				fmt.Fprintf(&b, "### %s\n\n", t.Name)
				if t.Doc != "" {
					b.WriteString(t.Doc + "\n\n")
				}
				if t.Type.Kind == idl.Enum {
					b.WriteString("| Value | Description |\n| --- | --- |\n")
					for _, v := range t.Type.Values {
						fmt.Fprintf(&b, "| `%s` | %s |\n", v.Name, cell(v.Doc))
					}
					b.WriteString("\n")
				} else {
					fieldTable(&b, t.Type)
				}
			}
		}
		if len(iface.Errors) > 0 {
			b.WriteString("## Errors\n\n| Error | Go type | Description |\n| --- | --- | --- |\n")
			for _, e := range iface.Errors {
				typ := GoName(e.Name)
				if !strings.HasSuffix(typ, "Error") {
					typ += "Error"
				}
				fmt.Fprintf(&b, "| `%s` | `%s` | %s |\n", e.Name, typ, cell(e.Doc))
			}
			b.WriteString("\n")
		}
		pages = append(pages, Page{Path: "interfaces/" + pkg + ".md", NavTitle: name, Content: b.String()})
	}

	var ch strings.Builder
	ch.WriteString("# API changes\n\n<!-- Generated by `make docs-reference`. Do not edit. -->\n\n")
	ch.WriteString("Every sdvarlink release publishes what changed in systemd's Varlink API between the releases it generates bindings for. ")
	ch.WriteString("Use it to decide which versioned package to import, and which methods to guard with `Supports()`.\n\n")
	for i := len(releases) - 1; i > 0; i-- {
		ch.WriteString(DiffMarkdown(releases[i-1].Version, releases[i].Version, Diff(releases[i-1].Interfaces, releases[i].Interfaces)))
	}
	pages = append(pages, Page{Path: "api-changes.md", Content: ch.String()})
	return pages
}

func hasFD(cfg *Config, t *idl.Type) bool {
	for _, f := range t.Fields {
		ft := f.Type
		if ft.Kind == idl.Nullable {
			ft = ft.Elem
		}
		if ft.Kind == idl.Int && strings.HasSuffix(strings.ToLower(f.Name), strings.ToLower(cfg.FDFieldSuffix)) {
			return true
		}
	}
	return false
}

func goSignature(m *idl.Method) string {
	name := GoName(m.Name)
	in := ""
	if len(m.In.Fields) > 0 {
		in = ", in " + name + "In"
	}
	out := "*" + name + "Out"
	if len(m.Out.Fields) == 0 {
		out = "*struct{}"
	}
	single := fmt.Sprintf("func (c *Client) %s(ctx context.Context%s) (%s, error)", name, in, out)
	if len(m.Out.Fields) == 0 {
		single = fmt.Sprintf("func (c *Client) %s(ctx context.Context%s) error", name, in)
	}
	stream := func(n string) string {
		return fmt.Sprintf("func (c *Client) %s(ctx context.Context%s) iter.Seq2[%s, error]", n, in, out)
	}
	switch m.More {
	case idl.MoreRequired:
		return stream(name)
	case idl.MoreSupported:
		return single + "\n" + stream(name+"More")
	}
	return single
}

func fieldTable(b *strings.Builder, t *idl.Type) {
	b.WriteString("| Field | Type | Description |\n| --- | --- | --- |\n")
	for _, f := range t.Fields {
		fmt.Fprintf(b, "| `%s` | `%s` | %s |\n", f.Name, cell(f.Type.String()), cell(f.Doc))
	}
	b.WriteString("\n")
}

func cell(s string) string {
	s = strings.ReplaceAll(s, "|", "\\|")
	s = strings.ReplaceAll(s, "\n", " ")
	return s
}
