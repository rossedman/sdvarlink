package gen

import (
	"go/parser"
	"go/token"
	"strings"
	"testing"
)

func TestAlias(t *testing.T) {
	t.Parallel()
	const src = `package demo

import "context"

type Client struct{}
type hidden struct{}
type Mode string

const (
	ModeA Mode = "a"
	modeB Mode = "b"
)

var ErrGone = error(nil)
var internal = 1

func New(c int) *Client { return nil }
func Dial(ctx context.Context, path string, opts ...string) (*Client, error) { return nil, nil }
func helper() {}
func (c *Client) Method() {}
`
	tests := []struct {
		name    string
		src     string
		version string
		want    []string
		not     []string
		wantErr bool
	}{
		{
			name:    "full package",
			src:     src,
			version: "260",
			want: []string{
				"// Code generated by sdvarlink-gen. DO NOT EDIT.",
				"// Package demo re-exports example.com/m/systemd/v260/demo, the bindings for the newest",
				"(v260).",
				"package demo",
				"v260 \"example.com/m/systemd/v260/demo\"",
				"\"github.com/rossedman/sdvarlink/varlink\"",
				"// New calls v260.New.\nfunc New(c int) *Client {\n\treturn v260.New(c)\n}",
				"func Dial(ctx context.Context, path string, opts ...string) (*Client, error) {\n\treturn v260.Dial(ctx, path, opts...)\n}",
				"type (\n\tClient = v260.Client\n\tMode   = v260.Mode\n)",
				"const (\n\tModeA = v260.ModeA\n)",
				"var (\n\tErrGone = v260.ErrGone\n)",
				"_ varlink.Caller",
			},
			not: []string{"hidden", "modeB", "internal", "helper", "Method"},
		},
		{
			name:    "only functions",
			src:     "package only\n\nfunc F() {}\n",
			version: "1",
			want:    []string{"package only", "func F() {\n\treturn v1.F()\n}"},
			not:     []string{"type (", "const (", "// Variables re-exported"},
		},
		{
			name:    "empty package",
			src:     "package empty\n",
			version: "1",
			want:    []string{"package empty", "_ context.Context"},
			not:     []string{"type (", "const (", "// Variables re-exported"},
		},
		{name: "syntax error", src: "package", wantErr: true},
		{name: "empty source", src: "", wantErr: true},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			out, err := Alias([]byte(tc.src), "example.com/m/systemd/v260/demo", tc.version)
			if tc.wantErr {
				if err == nil {
					t.Fatalf("Alias succeeded:\n%s", out)
				}
				if out != nil {
					t.Errorf("out = %q, want nil", out)
				}
				return
			}
			if err != nil {
				t.Fatal(err)
			}
			got := string(out)
			for _, w := range tc.want {
				if !strings.Contains(got, w) {
					t.Errorf("output lacks %q\n%s", w, got)
				}
			}
			for _, n := range tc.not {
				if strings.Contains(got, n) {
					t.Errorf("output unexpectedly contains %q", n)
				}
			}
			if _, err := parser.ParseFile(token.NewFileSet(), "", out, 0); err != nil {
				t.Errorf("output does not parse: %v", err)
			}
		})
	}
}
